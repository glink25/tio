export function BuiltinIcon({
  name,
  color = 'default',
  className,
  ...props
}: Omit<IconProps, 'weight' | 'color'> & { name: BuiltinIconName; color?: BuiltinIconColor }) {
  const Icon = builtinIcons[name];
  return (
    <Icon
      {...props}
      className={[iconColorClasses[color], className].filter(Boolean).join(' ')}
      weight="fill"
    />
  );
}

